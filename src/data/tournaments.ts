const registrationOpenDate = (tournament: TournamentSeed): string | undefined => {
  if (tournament.registrationOpens) return tournament.registrationOpens
  if (!tournament.registrationCloses) return undefined
  const closes = new Date(tournament.registrationCloses).getTime()
  return new Date(closes - 14 * 24 * 60 * 60 * 1000).toISOString()
}

export const tournaments: Tournament[] = seedTournaments.map((tournament) => {
  const prize = toDemoPrize(tournament.prize)
  return {
    ...tournament,
    prize,
    entryFee: entryFeeForPrize(prize),
    currency: 'PHP',
    published: tournament.status !== 'draft',
    registrationOpens: registrationOpenDate(tournament),
    createdAt: '2026-08-01T09:00:00',
  }
})

export const tournamentById = (id: string): Tournament | undefined =>
  tournaments.find((tournament) => tournament.id === id)

export const tournamentsByGame = (game: string): Tournament[] =>
  tournaments.filter((tournament) => tournament.game === game)

export const featuredTournaments = (): Tournament[] =>
  tournaments.filter((tournament) => tournament.featured)

export const eventCountForGame = (game: string): number =>
  tournaments.filter((tournament) => tournament.game === game).length

export const totalPrizePool = (): number =>
  tournaments.reduce((total, tournament) => total + tournament.prize, 0)
